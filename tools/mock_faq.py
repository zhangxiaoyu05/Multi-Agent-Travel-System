# =============================================================================
# FAQ 工具函数
# =============================================================================


@tool
def search_faq(query: str) -> str:
    """搜索 FAQ 知识库。

    根据用户问题中的关键词匹配 FAQ 条目，返回相关答案。
    支持的类别包括：签证、支付、退改、天气、小费、网络、交通、安全、美食、语言等。

    Args:
        query: 用户的问题文本

    Returns:
        匹配的 FAQ 答案文本。如果没有精确匹配，返回兜底提示。
    """
    query_lower = query.lower()

    # 关键词精确匹配
    for key, answer in _FAQ_DB.items():
        if key in query or key.lower() in query_lower:
            return answer

    # 模糊匹配（英文/缩写）
    fuzzy_map = {
        "visa": "签证",
        "payment": "支付",
        "cancel": "退改",
        "refund": "退改",
        "weather": "天气",
        "tip": "小费",
        "wifi": "网络",
        "internet": "网络",
        "transport": "交通",
        "taxi": "交通",
        "subway": "交通",
        "safety": "安全",
        "food": "美食",
        "eat": "美食",
        "restaurant": "美食",
        "language": "语言",
        "english": "语言",
    }
    for en_key, cn_key in fuzzy_map.items():
        if en_key in query_lower:
            return _FAQ_DB[cn_key]

    # 兜底
    return (
        "您的问题已记录，当前 AI 客服暂未覆盖该问题的详细解答。\n"
        "建议：\n"
        "1. 尝试用其他方式描述您的问题\n"
        "2. 输入「人工」转接人工客服\n"
        "3. 常见问题：签证、支付、退改、天气、交通、网络、美食、安全"
    )
