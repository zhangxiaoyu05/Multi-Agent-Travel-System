"""Mock 库存查询工具（酒店、门票、车辆）

MVP 阶段返回模拟库存数据。
Phase 8 对接真实供应商 API（酒店 CRS、票务系统、车队调度）。
"""

from langchain.tools import tool


@tool
def query_inventory(city: str, date: str, pax: int) -> str:
    """查询指定城市在指定日期的酒店、门票、车辆库存情况。

    用于行程规划时确认资源可用性，确保推荐的行程是可预订的。

    Args:
        city: 城市名称（中文）
        date: 日期，格式 YYYY-MM-DD
        pax: 出行人数

    Returns:
        库存信息文本，包含酒店、门票、车辆可用情况和建议。
    """
    # 根据人数推荐房型
    rooms = max(1, (pax + 1) // 2)  # 2人一间

    return (
        f"[{city}] {date} 库存查询（{pax}人出行）\n"
        f"\n"
        f"住宿：\n"
        f"  - 市中心四星酒店：约 $80-120/间/晚，当前可订 {rooms} 间\n"
        f"  - 精品客栈/民宿：约 $50-80/间/晚，可订，建议提前 3 天确认\n"
        f"  - 国际五星酒店：约 $180-300/间/晚，可订\n"
        f"\n"
        f"门票：\n"
        f"  - 主要景点均可在线预约\n"
        f"  - 热门景点建议提前 1-3 天在官方小程序购票\n"
        f"  - 临时可安排快速通道（附加费约 $15/人）\n"
        f"\n"
        f"交通：\n"
        f"  - 7 座商务车（含司导）：约 $120-150/天\n"
        f"  - 5 座轿车（含司机）：约 $70-90/天\n"
        f"  - 高铁/动车票：建议通过 12306 提前购买\n"
        f"\n"
        f"整体可用率：约 92%\n"
        f"建议：库存充足，可正常安排行程。建议尽早预订以锁定最优价格。"
    )
